def translate_eiken5():
    e5_path = 'scratch/eiken5/eiken5_all.json'
    if not os.path.exists(e5_path):
        print("Error: scratch/eiken5/eiken5_all.json not found.")
        return

    with open(e5_path, 'r', encoding='utf-8') as f:
        e5_items = json.load(f)

    translated_items = []
    missing_mapping_count = 0

    for item in e5_items:
        word = item["word"].lower().strip()
        meaning_vi = E5_TRANSLATIONS.get(word, "")
        
        # Resilient lookup: handle punctuation / spaces
        if not meaning_vi:
            clean_word = word.replace("\\:", ":").replace(" let\\", "let").replace("check \\~ out", "check ~ out")
            meaning_vi = E5_TRANSLATIONS.get(clean_word, "")
            
        # Fallback to similar checks
        if not meaning_vi:
            # check if double key exists
            for k, v in E5_TRANSLATIONS.items():
                if k in word or word in k:
                    meaning_vi = v
                    break

        if meaning_vi:
            item["meaning_vi"] = meaning_vi
        else:
            print(f"Warning: No translation found for word '{word}'")
            missing_mapping_count += 1
            item["meaning_vi"] = "từ vựng" # Fallback safe placeholder
            
        translated_items.append(item)

    print(f"Translated Eiken 5 Kyu set: {len(translated_items)} words. Missing mappings: {missing_mapping_count}")
    
    # Save the all translations JSON
    os.makedirs('scratch', exist_ok=True)
    with open('scratch/all_translations.json', 'w', encoding='utf-8') as out:
        json.dump(translated_items, out, ensure_ascii=False, indent=2)

    # Perform Merging Pipeline into src/data/dictionary.ts
    print("Executing Merging Phase...")
    dict_path = 'src/data/dictionary.ts'
    
    with open('scratch/all_translations.json', 'r', encoding='utf-8') as f:
        translations = json.load(f)
        
    translation_map = {item['word'].lower().strip(): item for item in translations}
    
    with open(dict_path, 'r', encoding='utf-8') as f:
        lines = f.readlines()
        
    updated_lines = []
    merge_count = 0
    
    # Matching regex supporting single-quoted key pairs
    line_pattern = re.compile(
        r"(\{\s*word:\s*'([^']+)',\s*meaning_vi:\s*')([^']*)('\s*,\s*meaning_ja:\s*'([^']*)')(\s*,\s*level:\s*'([^']+)'\s*,\s*difficulty:\s*\d\s*(?:,\s*emoji:\s*'[^']+'\s*)?\})"
    )
    
    for line in lines:
        match = line_pattern.search(line)
        if match:
            prefix, word, old_vi, mid, old_ja, suffix, lvl = match.groups()
            word_clean = word.lower().strip()
            
            # Target ONLY Eiken 5 Kyu for Wave 1 safety
            if lvl == 'Eiken 5 Kyu' and word_clean in translation_map:
                trans = translation_map[word_clean]
                new_vi = trans['meaning_vi']
                
                if new_vi and old_vi == "":
                    # Safely replace only the empty meaning_vi quotes
                    line = f"{prefix}{new_vi}{mid}{suffix},\n"
                    # Handle optional trailing comma difference
                    if not line.rstrip().endswith(','):
                        line = line.rstrip() + ',\n'
                    merge_count += 1
        updated_lines.append(line)
        
    with open(dict_path, 'w', encoding='utf-8') as f:
        f.writelines(updated_lines)
        
    print(f"Successfully merged {merge_count} Eiken 5 Kyu Vietnamese translations into {dict_path}!")

if __name__ == "__main__":
    translate_eiken5()
